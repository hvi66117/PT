inline void PhongThanInitializeWireHeader(PHONGTHAN_WIRE_HEADER* pHeader,
	PHONGTHAN_U16 nMessageType, PHONGTHAN_U32 nPacketSize,
	PHONGTHAN_U16 nFlags, PHONGTHAN_U32 nSequence)
{
	if (!pHeader)
		return;
	pHeader->Magic = PHONGTHAN_WIRE_MAGIC;
	pHeader->Version = PHONGTHAN_WIRE_VERSION;
	pHeader->HeaderSize = (PHONGTHAN_U16)sizeof(PHONGTHAN_WIRE_HEADER);
	pHeader->MessageType = nMessageType;
	pHeader->Flags = nFlags;
	pHeader->PacketSize = nPacketSize;
	pHeader->Sequence = nSequence;
}

inline int PhongThanIsWirePacket(const void* pData, PHONGTHAN_U32 nAvailableSize)
{
	if (!pData || nAvailableSize < sizeof(PHONGTHAN_WIRE_HEADER))
		return 0;
	const PHONGTHAN_WIRE_HEADER* pHeader =
		(const PHONGTHAN_WIRE_HEADER*)pData;
	return pHeader->Magic == PHONGTHAN_WIRE_MAGIC;
}

inline int PhongThanValidateWireHeader(const PHONGTHAN_WIRE_HEADER* pHeader,
	PHONGTHAN_U32 nAvailableSize)
{
	if (!pHeader || pHeader->Magic != PHONGTHAN_WIRE_MAGIC ||
		pHeader->Version != PHONGTHAN_WIRE_VERSION ||
		pHeader->HeaderSize != sizeof(PHONGTHAN_WIRE_HEADER) ||
		pHeader->PacketSize < sizeof(PHONGTHAN_WIRE_HEADER) ||
		pHeader->PacketSize > PHONGTHAN_WIRE_MAX_PACKET_SIZE ||
		pHeader->PacketSize > nAvailableSize)
	{
		return 0;
	}
	return 1;
}

inline int PhongThanValidateItemSnapshot(const void* data, PHONGTHAN_U32 size)
{
	if (!data || size != sizeof(PHONGTHAN_ITEM_SNAPSHOT)) return 0;
	const PHONGTHAN_ITEM_SNAPSHOT* item = (const PHONGTHAN_ITEM_SNAPSHOT*)data;
	// Old untagged level 0..15 or tagged rule (bits 8..23) plus level.
	const PHONGTHAN_U32 upgrade=(PHONGTHAN_U32)item->UpgradeLevel;
	if(upgrade>15 && ((upgrade&0xff0000f0u)!=0x40000000u || !(upgrade&15u) || !((upgrade>>8)&65535u)))return 0;
	return PhongThanValidateWireHeader(&item->Header, size) &&
		item->Header.PacketSize == size &&
		item->Header.MessageType == PHONGTHAN_MSG_INVENTORY_ITEM_SNAPSHOT &&
		item->Header.Flags == PHONGTHAN_WIRE_FLAG_RESPONSE;
}

