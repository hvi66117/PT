typedef char PHONGTHAN_U32_MUST_BE_4_BYTES[(sizeof(PHONGTHAN_U32) == 4) ? 1 : -1];
typedef char PHONGTHAN_S32_MUST_BE_4_BYTES[(sizeof(PHONGTHAN_S32) == 4) ? 1 : -1];

