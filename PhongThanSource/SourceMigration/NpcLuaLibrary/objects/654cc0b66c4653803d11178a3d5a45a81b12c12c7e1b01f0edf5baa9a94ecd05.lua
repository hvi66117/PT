function todayfreetimes(value)
  local free = 1
  if (value >= 2 ^ 5) then
    free = GetBit(value, 6) + 2 * GetBit(value, 7) + 4 * GetBit(value, 8) + 1
    for i = 6, 8 do
      value = SetBit(value, i, 0)
    end
  end
  return value, free
end

